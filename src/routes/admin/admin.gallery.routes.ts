const router = new Router();

/**
 * @openapi
 * /admin/gallery/cos/sts:
 *   post:
 *     tags: [adminGallery]
 *     summary: 创建sts
 *     security:
 *       - bearerAuth: []
 *     responses:
 *       '200':
 *         description: 成功
 *         content:
 *           application/json:
 *             schema:
 *               $ref: '#/components/schemas/SuccessObject'
 *       '401':
 *         description: 未授权
 *         content:
 *           application/json:
 *             schema:
 *               $ref: '#/components/schemas/ErrorResponse'
 */
router.post(
  "/gallery/cos/sts",
  requireAdminPage(ADMIN_PAGE_GALLERY),
  async (ctx) => {
    try {
      const body = adminGalleryCosStsSchema.parse(ctx.request.body);
      const data = await AdminGalleryService.createCosStsCredential({
        biz: body.biz,
        fileName: body.fileName,
        fileType: body.fileType,
        fileSize: body.fileSize,
        withThumb: body.withThumb,
      });
      success(ctx, data, "获取上传凭证成功");
    } catch (e) {
      if (e instanceof z.ZodError) {
        error(ctx, "参数验证失败", ErrorCodes.PARAM_ERROR, 400);
        return;
      }
      const msg = e instanceof Error ? e.message : "获取上传凭证失败";
      error(ctx, msg, ErrorCodes.PARAM_ERROR, 400);
    }
  },
);

/**
 * @openapi
 * /admin/gallery/images:
 *   post:
 *     tags: [adminGallery]
 *     summary: 创建images
 *     security:
 *       - bearerAuth: []
 *     responses:
 *       '200':
 *         description: 成功
 *         content:
 *           application/json:
 *             schema:
 *               $ref: '#/components/schemas/SuccessObject'
 *       '401':
 *         description: 未授权
 *         content:
 *           application/json:
 *             schema:
 *               $ref: '#/components/schemas/ErrorResponse'
 */
router.post(
  "/gallery/images",
  requireAdminPage(ADMIN_PAGE_GALLERY),
  async (ctx) => {
    try {
      const body = adminGalleryRecordSchema.parse(ctx.request.body);
      const admin = ctx.state.admin!;
      const row = await AdminGalleryService.recordUploadedImage({
        biz: body.biz,
        url: body.url,
        storageKey: body.storageKey,
        mimeType: body.mimeType,
        size: body.size,
        width: body.width,
        height: body.height,
        thumbUrl: body.thumbUrl,
        thumbKey: body.thumbKey,
        createdByAdminId: String(admin.id || ""),
        createdByAdminUsername: admin.username,
      });
      success(ctx, row, "图片入库成功");
    } catch (e) {
      if (e instanceof z.ZodError) {
        error(ctx, "参数验证失败", ErrorCodes.PARAM_ERROR, 400);
        return;
      }
      const msg = e instanceof Error ? e.message : "图片入库失败";
      error(ctx, msg, ErrorCodes.PARAM_ERROR, 400);
    }
  },
);

/**
 * @openapi
 * /admin/gallery/images:
 *   get:
 *     tags: [adminGallery]
 *     summary: 获取images
 *     security:
 *       - bearerAuth: []
 *     responses:
 *       '200':
 *         description: 成功
 *         content:
 *           application/json:
 *             schema:
 *               $ref: '#/components/schemas/SuccessObject'
 *       '401':
 *         description: 未授权
 *         content:
 *           application/json:
 *             schema:
 *               $ref: '#/components/schemas/ErrorResponse'
 */
router.get(
  "/gallery/images",
  requireAdminPage(ADMIN_PAGE_GALLERY),
  async (ctx) => {
    try {
      const q = adminGalleryListQuerySchema.parse(ctx.query);
      const { items, total, page, limit } = await AdminGalleryService.listImages({
        page: q.page,
        limit: q.limit,
        biz: q.biz,
      });
      paginatedSuccess(ctx, items, total, page, limit, "获取图库列表成功");
    } catch (e) {
      if (e instanceof z.ZodError) {
        error(ctx, "参数验证失败", ErrorCodes.PARAM_ERROR, 400);
        return;
      }
      const msg = e instanceof Error ? e.message : "获取图库列表失败";
      error(ctx, msg, ErrorCodes.INTERNAL_ERROR, 500);
    }
  },
);

/**
 * @openapi
 * /admin/gallery/images/{id}:
 *   delete:
 *     tags: [adminGallery]
 *     summary: 删除:id
 *     security:
 *       - bearerAuth: []
 *     responses:
 *       '200':
 *         description: 成功
 *         content:
 *           application/json:
 *             schema:
 *               $ref: '#/components/schemas/SuccessObject'
 *       '401':
 *         description: 未授权
 *         content:
 *           application/json:
 *             schema:
 *               $ref: '#/components/schemas/ErrorResponse'
 */
router.delete(
  "/gallery/images/:id",
  requireAdminPage(ADMIN_PAGE_GALLERY),
  async (ctx) => {
    try {
      const ok = await AdminGalleryService.hideImage(ctx.params.id || "");
      if (!ok) {
        error(ctx, "记录不存在或 id 无效", ErrorCodes.NOT_FOUND, 404);
        return;
      }
      success(ctx, { hidden: true }, "已从图库移除");
    } catch (e) {
      error(
        ctx,
        e instanceof Error ? e.message : "移除失败",
        ErrorCodes.INTERNAL_ERROR,
        500,
      );
    }
  },
);

